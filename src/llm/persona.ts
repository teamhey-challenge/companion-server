const KST_NOTE = "";

const FUEL_LABEL: Record<string, string> = { "10": "전기차", "7": "LPG차", "8": "가스차", "9": "가스차", "11": "수소차" };

/** 차량 상태를 모델이 오해하지 않게 한국어 문장으로 풀어 쓴다(예: fuelType=10 을 "연료 10%"로 읽는 일 방지). 모르는 키는 key=value 그대로. */
export function describeCtx(ctx: Ctx): string {
  const parts: string[] = [];
  for (const [k, v] of Object.entries(ctx)) {
    if (v === null || v === undefined) continue;
    switch (k) {
      case "gear": parts.push(v === "P" ? "정차(P)" : "주행 중"); break;
      case "speedKmh": break; // 속도는 말하지 않는 규칙이라 프롬프트에 넣지 않는다.
      case "naviGuiding": parts.push(v ? "내비 안내 중" : "내비 안내 없음"); break;
      case "wiper": parts.push(/^(off|0|false|none)$/i.test(String(v)) || v === false || v === 0 ? "와이퍼 꺼짐" : "와이퍼 작동 중(실제 강수량은 모름)"); break;
      case "rangeKm": parts.push(`주행가능거리 ${v}km(연료·배터리 퍼센트는 모름)`); break;
      case "fuelType": parts.push(`차 종류 ${FUEL_LABEL[String(v)] ?? "내연기관차"}(숫자 코드이며 퍼센트가 아님)`); break;
      case "headlight": parts.push(v ? "헤드라이트 켜짐" : "헤드라이트 꺼짐"); break;
      case "doorOpen": parts.push(v ? "문 열림" : "문 닫힘"); break;
      default: parts.push(`${k}=${v}`);
    }
  }
  return parts.join(", ");
}

export function buildSystem(p: PersonaInput): string {
  const out: string[] = [CORE, STYLE[p.speech]];
  if (p.nickname) out.push(`운전자를 "${p.nickname}"${p.speech === "jondaetmal" ? "님" : ""}(이)라고 부른다. 매 문장 부르지 말고 가끔만 부른다.`);
  if (p.driving) {
    out.push(
      p.proactive
        ? "지금은 주행 중이다. 먼저 거는 말이므로 최대 2문장, 한 문장은 15자 안팎으로 아주 짧게 말한다."
        : "지금은 주행 중이다. 답은 반드시 마침표·물음표·느낌표 기준 2문장 이하(되묻는 질문도 센다. 3문장째는 쓰지 않고 멈춘다. 공감 한마디(1문장)와 짧은 질문 또는 제안 하나(1문장)면 충분하다. 인사·공감·질문 세 가지를 모두 넣지 않는다. ~하는 게 좋겠어 같은 권유 문장을 덧붙이지 않는다)로, 합쳐서 50자 안팎으로 짧게 한다. 설명을 요구하는 복잡한 질문만 3문장까지 허용한다. 추천은 한 문장에 두세 가지를 묶고 되묻지 않는다. 목록과 긴 설명은 쓰지 않는다.",
    );
  } else {
    out.push("지금은 정차 중이다. 편하게 수다를 떨되 보통 1~3문장으로 답한다. 4문장을 넘기지 않는다.");
  }
  const ctxLine = describeCtx(p.ctx);
  if (ctxLine) out.push(`[차량 상태] ${ctxLine}${KST_NOTE}`);
  if (p.memories.length) {
    out.push(
      `[기억] 운전자가 예전에 직접 말한 것들이다(최신순):\n${p.memories.map((m) => `- ${m.text}`).join("\n")}\n` +
        "운전자가 기억을 묻거나(예: 내가 뭐 좋아한다고 했지?) 이번 말과 직접 이어지는 기억이 있을 때만 그중 하나를 자연스럽게 언급한다. 직접 관련 없는 잡담에는 기억을 꺼내지 않는다. 기억에 적힌 내용만 말하고, 거기서 일정·요일·장소를 추측하지 않는다. 기억에 없는 건 아는 척하지 않는다. 도착·출발·퇴근·잠자리 같은 마무리 인사에 내일·오늘 챙길 일정(면접, 발표, 약속)이 기억에 있으면 그 일정을 한마디 응원으로 반드시 곁들인다(예: 내일 발표 잘 하자!). 휴식 인사만 하고 끝내지 않는다.",
    );
  }
  if (p.recent?.length) {
    out.push("[최근 대화]\n" + p.recent.map((r) => (r.u ? `운전자 말: ${r.u}\n내가 한 답: ${r.a}` : `내가 먼저 한 말: ${r.a}`)).join("\n"));
  }
  if (p.proactive) out.push(`[먼저 말 걸기: ${p.proactive.reason}] ${p.proactive.instruction}`);
  return out.join("\n\n");
}

